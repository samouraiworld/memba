#!/usr/bin/env node
/**
 * Generates frontend/src/lib/chain/evm/manifest.generated.ts from deployments/evm/<chainId>.json, the
 * chain-verified manifest (docs/evm/README.md). The JSON is the only source: the app imports this typed copy,
 * never the JSON. The checks below run first, so a malformed manifest never reaches the app.
 *
 * Usage (from frontend/): node scripts/gen-evm-manifest.mjs [--check]
 *   --check  fail if the committed module differs from a fresh generation (CI)
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const MANIFEST_DIR = join(here, "../../deployments/evm")
const OUT = join(here, "../src/lib/chain/evm/manifest.generated.ts")

const ADDRESS = /^0x[0-9a-fA-F]{40}$/
const HASH = /^0x[0-9a-f]{64}$/
const KEY = /^[a-z][A-Za-z0-9]*$/

function fail(msg) {
    console.error(`gen-evm-manifest: ${msg}`)
    process.exit(1)
}

/** Keeps only what the app uses; `source` and `versionGetter` serve the Foundry checks. */
function contract(file, key, c) {
    const at = `${file} contracts.${key}`
    if (!KEY.test(key)) fail(`${at}: key must be camelCase`)
    if (!ADDRESS.test(c.address ?? "")) fail(`${at}: bad address`)
    if (!HASH.test(c.codehash ?? "")) fail(`${at}: bad codehash`)
    const out = { address: c.address, codehash: c.codehash }
    if (c.version !== undefined) {
        if (typeof c.version !== "string" || !c.version) fail(`${at}: bad version`)
        out.version = c.version
    }
    if (c.build !== undefined) {
        if (!Number.isInteger(c.build.release) || !Number.isInteger(c.build.build)) fail(`${at}: bad build`)
        out.build = { release: c.build.release, build: c.build.build }
    }
    if (c.proxy !== undefined) {
        if (!ADDRESS.test(c.proxy.implementation ?? "") || !HASH.test(c.proxy.implementationCodehash ?? "")) fail(`${at}: bad proxy`)
        out.proxy = { implementation: c.proxy.implementation, implementationCodehash: c.proxy.implementationCodehash }
    }
    return out
}

export function render() {
    const files = readdirSync(MANIFEST_DIR).filter((f) => /^\d+\.json$/.test(f)).sort((a, b) => parseInt(a) - parseInt(b))
    if (files.length === 0) fail(`no <chainId>.json in ${MANIFEST_DIR}`)
    const chains = {}
    let keys = null
    for (const file of files) {
        const m = JSON.parse(readFileSync(join(MANIFEST_DIR, file), "utf8"))
        const chainId = parseInt(file)
        if (m.chainId !== chainId) fail(`${file}: chainId ${m.chainId} does not match the file name`)
        if (typeof m.network !== "string" || !m.verified?.date || !Number.isInteger(m.verified?.block)) fail(`${file}: bad network/verified`)
        const contractKeys = Object.keys(m.contracts ?? {})
        if (contractKeys.length === 0) fail(`${file}: no contracts`)
        const sorted = [...contractKeys].sort().join(",")
        if (keys !== null && sorted !== keys) fail(`${file}: contract keys differ from the other chains (one key set for the app)`)
        keys = sorted
        const contracts = Object.fromEntries(contractKeys.map((k) => [k, contract(file, k, m.contracts[k])]))
        const deny = {}
        for (const [k, d] of Object.entries(m.deny ?? {})) {
            if (!ADDRESS.test(d.address ?? "") || typeof d.reason !== "string" || !d.reason) fail(`${file} deny.${k}: bad entry`)
            const listed = contractKeys.find((c) => contracts[c].address.toLowerCase() === d.address.toLowerCase())
            if (listed) fail(`${file}: ${listed} is also denied as ${k}`)
            deny[k] = { address: d.address, reason: d.reason }
        }
        chains[chainId] = { network: m.network, verified: { date: m.verified.date, block: m.verified.block }, contracts, deny }
    }
    const sources = files.map((f) => relative(join(here, "../.."), join(MANIFEST_DIR, f))).join(", ")
    return `// GENERATED by frontend/scripts/gen-evm-manifest.mjs from ${sources}. Do not edit:
// change the JSON (checked against the chains by contracts/evm/test/manifest), then run
// \`node scripts/gen-evm-manifest.mjs\` in frontend/.

export const EVM_MANIFEST = ${JSON.stringify(chains, null, 4)} as const
`
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
    const next = render()
    if (process.argv.includes("--check")) {
        const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
        if (current !== next) fail(`${relative(process.cwd(), OUT)} is stale. Run \`node scripts/gen-evm-manifest.mjs\` in frontend/ and commit the result.`)
        console.log("manifest.generated.ts matches deployments/evm")
    } else {
        writeFileSync(OUT, next)
        console.log(`wrote ${relative(process.cwd(), OUT)}`)
    }
}
