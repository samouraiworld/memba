/**
 * Gno source for the generated DAO realm, template version `memba-dao/2`.
 *
 * The realm is split into sections so each rule can be reviewed on its own.
 * Sections are raw strings (no escapes are processed on the TypeScript side),
 * so the Gno text below is exactly what gets deployed. Only `realmHeader`,
 * `realmState` and `realmGenesis` interpolate values, and every value they
 * receive has already been validated by `generateDAOCode`.
 *
 * Rules (each has a native test in daoTemplate.v2.gno.test.ts):
 *  1. no privileged roles: membership, roles and archive change only through
 *     executed proposals;
 *  2. genesis checks in init();
 *  3. propose validates everything before the first write;
 *  4. votes use overflow-safe comparisons over bounded integers;
 *  5. EXPIRED, LAPSED and INVALIDATED are derived on read;
 *  6. execute re-validates the stored action against current state;
 *  7. events for creation, votes, execution and archive;
 *  8. caller identity from cur.Previous();
 *  9. bounded, paginated JSON reads;
 * 11. actions stored by value, handler fixed by kind, no cross-realm calls,
 *     addresses are the only identity in member rows, no recover;
 * 12. Render escapes every user string.
 */

